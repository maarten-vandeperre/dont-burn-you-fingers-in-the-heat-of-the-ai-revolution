#!/usr/bin/env bash
# =============================================================================
# Ansible: Red Hat Ansible Automation Platform (AAP) 2.6 + two playbooks + two workflows
# (install with a manual-approval delete, and a standalone delete) + the Developer Hub wiring
# (the default Ansible/rhaap plugin and a software template that launches a workflow).
#
# AAP 2.6 fronts every component (Controller, Hub, EDA) with a single Platform Gateway: one
# Route, one login, one token endpoint. This demo only enables Controller (Hub and EDA are
# disabled in stack/ansible/aap.yaml) but every API call below still goes through the gateway's
# "/api/controller/v2/..." path, not a bare "/api/v2/..." -- that prefix is the one thing that's
# different from the older, Controller-only AWX/AAP API docs you'll find scattered online.
#
# Needs a real Ansible Automation Platform subscription (registry.redhat.io image pull access).
# See ansible/README.md "Red Hat subscription and the image pull secret" -- setup() below checks
# for it and tells you exactly what's missing if it's not there yet.
#
#   ./deploy.sh ansible setup       Operator, AAP instance, demo namespace/credential, then
#                                   bootstrap() wires the Project, Credential, Inventory, the
#                                   3 Job Templates and the 2 Workflow Job Templates in Controller
#   ./deploy.sh ansible bootstrap   Re-run only the Controller-API bootstrap (idempotent: safe
#                                   after editing ansible/job-templates.json or ansible/workflows/*.json)
#   ./deploy.sh ansible token       Print the AAP API token Developer Hub / software templates use
#   ./deploy.sh ansible urls        AAP Platform Gateway URL + how to get the admin password
#   ./deploy.sh ansible run <workflow>   Launch a workflow from the CLI (install-postgres-safe |
#                                   delete-postgres), for testing outside Developer Hub
#   ./deploy.sh ansible approve [id]     Approve the oldest (or a given) pending Workflow Approval
#   ./deploy.sh ansible deny [id]        Deny it instead
#   ./deploy.sh ansible status      Postgres Deployment in ansible-demo + pending approvals
#   ./deploy.sh ansible reset       Delete the demo PostgreSQL objects directly (oc, not Ansible) +
#                                   so a demo run starts clean (no stale approval blocking a retry)
#   ./deploy.sh ansible destroy     Remove the ansible-demo and aap namespaces
#                                   (the operator Subscription/CSV stay installed)
#
# Demo guide: docs/demos/11-ansible.md. Playbooks, workflow definitions and the "how to create and
# maintain these" documentation: ansible/README.md.
# =============================================================================
set -Eeuo pipefail

ANSIBLE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# ANSIBLE_DIR is stack/ansible -- the repository root (where the top-level ansible/ folder with
# job-templates.json and workflows/*.json lives) is two levels up, not one.
ROOT_DIR="$(cd "${ANSIBLE_DIR}/../.." && pwd)"
AAP_NS="aap"
DEMO_NS="ansible-demo"
AAP_CR="ansible-automation-platform"
ADMIN_USER="admin"
PULL_SECRET="aap-registry-pull-secret"
GITLAB_NS="gitlab"
GITLAB_GROUP="ai-platform"
GITLAB_PROJECT="platform"

if [[ -t 1 ]]; then B=$'\e[1m'; G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; N=$'\e[0m'; else B=""; G=""; Y=""; R=""; N=""; fi
step() { echo; echo "${B}==> $*${N}"; }
ok()   { echo "    ${G}OK${N} $*"; }
info() { echo "    $*"; }
warn() { echo "    ${Y}WARN${N} $*"; }
die()  { echo "${R}ERROR${N} $*" >&2; exit 1; }
need() { command -v "$1" >/dev/null || die "'$1' is required"; }
trap 'echo "${R}ERROR${N} failed at line ${LINENO}: ${BASH_COMMAND}" >&2' ERR

wait_until() {  # wait_until <seconds> <label> <command...>
  local timeout=$1 label=$2; shift 2
  local start; start=$(date +%s)
  until "$@" >/dev/null 2>&1; do
    if (( $(date +%s) - start > timeout )); then warn "timed out after ${timeout}s waiting for: ${label}"; return 1; fi
    sleep 5
  done
}
csv_ok() { oc get csv -n "$1" -o jsonpath='{range .items[*]}{.metadata.name} {.status.phase}{"\n"}{end}' 2>/dev/null | grep -q "^$2.* Succeeded"; }

# ----------------------------------------------------------------------------- AAP access
# Platform Gateway route: created automatically by the operator, named after the
# AnsibleAutomationPlatform CR's metadata.name (stack/ansible/aap.yaml).
aap_route() { oc get route "$AAP_CR" -n "$AAP_NS" -o jsonpath='{.spec.host}' 2>/dev/null; }
aap_url()   { local h; h=$(aap_route); [[ -n "$h" ]] && echo "https://${h}" || true; }
# Admin password Secret: "<CR name>-<admin_user>-password", auto-generated by the operator
# unless you pre-create it yourself -- same convention Red Hat's docs describe.
aap_admin_password() { oc get secret "${AAP_CR}-${ADMIN_USER}-password" -n "$AAP_NS" -o jsonpath='{.data.password}' 2>/dev/null | base64 -d 2>/dev/null; }
aap_ready() { [[ -n "$(aap_route)" ]] && curl -sk -o /dev/null -w '%{http_code}' "$(aap_url)/api/controller/v2/ping/" 2>/dev/null | grep -q '^200$'; }

# aap_bearer: a Platform Gateway OAuth token, fetched once per script run (POST
# /api/gateway/v1/tokens/ with basic auth) and reused for every Controller API call after that --
# this is the Gateway's one and only auth mechanism for the proxied "/api/controller/v2/..." API,
# replacing AWX's/AAP-Controller's old per-request basic auth.
aap_bearer() {
  if [[ -z "${AAP_BEARER:-}" ]]; then
    AAP_BEARER=$(curl -sk -u "${ADMIN_USER}:$(aap_admin_password)" -X POST -H 'Content-Type: application/json' \
      -d '{"description":"ansible.sh bootstrap session","scope":"write"}' \
      "$(aap_url)/api/gateway/v1/tokens/" 2>/dev/null | jq -r '.token // empty')
  fi
  [[ -n "${AAP_BEARER:-}" ]] || die "could not obtain a Platform Gateway token -- is AAP reachable and the admin password correct?"
  echo "$AAP_BEARER"
}

# aap_api <method> <path> [json-body]: talks to the Controller REST API through the gateway,
# e.g. aap_api GET /api/controller/v2/job_templates/
aap_api() {
  local method=$1 path=$2 body=${3:-}
  local args=(-sk -H "Authorization: Bearer $(aap_bearer)" -X "$method" -H 'Content-Type: application/json' "$(aap_url)${path}")
  [[ -n "$body" ]] && args+=(-d "$body")
  curl "${args[@]}"
}

# aap_get_id <endpoint> <name>: id of an existing Controller object by name, or empty
aap_get_id() { aap_api GET "/api/controller/v2/$1/?name=$(jq -rn --arg v "$2" '$v|@uri')" | jq -r '.results[0].id // empty'; }

gitlab_token() { oc get secret gitlab-automation-token -n "$GITLAB_NS" -o jsonpath='{.data.token}' 2>/dev/null | base64 -d 2>/dev/null || true; }
gitlab_url_with_token() {
  local host token; host=$(oc get route gitlab -n "$GITLAB_NS" -o jsonpath='{.spec.host}' 2>/dev/null)
  token=$(gitlab_token)
  [[ -n "$host" && -n "$token" ]] && echo "https://oauth2:${token}@${host}/${GITLAB_GROUP}/${GITLAB_PROJECT}.git" || true
}

# ----------------------------------------------------------------------------- setup
setup() {
  need oc; need curl; need jq
  oc whoami >/dev/null 2>&1 || die "not logged in: oc login"
  step "Operator: Ansible Automation Platform (redhat-operators, channel stable-2.6)"
  oc apply -f "${ANSIBLE_DIR}/operator.yaml" >/dev/null
  # The Subscription is named "ansible-automation-platform-operator", but the CSV it installs is
  # "aap-operator.v<version>" -- confirmed against a live cluster, not the Subscription's own name.
  wait_until 600 "AAP operator" csv_ok "$AAP_NS" aap-operator && ok "AAP operator installed"
  wait_until 300 "AnsibleAutomationPlatform CRD" oc get crd ansibleautomationplatforms.aap.ansible.com && ok "AAP CRD registered"

  step "Red Hat subscription: image pull secret"
  # Not every cluster needs this as a separate Secret: if the cluster-wide pull secret
  # (openshift-config/pull-secret) already has registry.redhat.io credentials entitled for AAP
  # (common on Red Hat-managed demo/workshop clusters), images pull fine without it -- the
  # kubelet falls back to the node-level secret and Controller/Gateway/PostgreSQL come up with
  # nothing more than a harmless "Unable to retrieve some image pull secrets" event. Only create
  # ${PULL_SECRET} (referenced by stack/ansible/aap.yaml's spec.controller.image_pull_secrets) if
  # pods actually sit in ImagePullBackOff below.
  if ! oc get secret "$PULL_SECRET" -n "$AAP_NS" >/dev/null 2>&1; then
    warn "Secret '${PULL_SECRET}' not found in '${AAP_NS}' -- continuing (many clusters' cluster-wide pull secret
    already covers registry.redhat.io). If Controller/Gateway/PostgreSQL pods below end up ImagePullBackOff, get a
    token-based pull secret from https://access.redhat.com/terms-based-registry/ (Ansible Automation Platform):
      oc create secret generic ${PULL_SECRET} -n ${AAP_NS} \\
        --type=kubernetes.io/dockerconfigjson --from-file=.dockerconfigjson=<downloaded-secret.json>
    See ansible/README.md 'Red Hat subscription and the image pull secret' for the full walkthrough, then re-run
    ./deploy.sh ansible setup."
  else
    # Belt and suspenders: stack/ansible/aap.yaml already sets this for the controller pods via
    # spec.controller.image_pull_secrets, but the gateway and PostgreSQL pods use the namespace's
    # "default" ServiceAccount, so link it there too -- the one mechanism that works regardless of
    # which CR fields a given AAP point release does or doesn't expose for those components.
    oc secrets link default "$PULL_SECRET" --for=pull -n "$AAP_NS" >/dev/null 2>&1 || true
    ok "pull secret present and linked to the 'default' ServiceAccount in ${AAP_NS}"
  fi

  step "AAP instance + demo namespace + credential"
  oc apply -k "$ANSIBLE_DIR" >/dev/null
  wait_until 180 "AAP admin password Secret" oc get secret "${AAP_CR}-${ADMIN_USER}-password" -n "$AAP_NS"
  wait_until 900 "AAP pods ready" bash -c "[[ \$(oc get pods -n ${AAP_NS} --no-headers 2>/dev/null | grep -c Running) -ge 4 ]]"
  wait_until 180 "Platform Gateway route" oc get route "$AAP_CR" -n "$AAP_NS"
  wait_until 300 "Controller API (through the gateway)" aap_ready && ok "AAP reachable at $(aap_url)"

  bootstrap
  info "Open $(aap_url) (${ADMIN_USER} / 'oc get secret ${AAP_CR}-${ADMIN_USER}-password -n ${AAP_NS}')"
  info "Then: ./deploy.sh rhdh   (wires the Ansible plugin + the two software templates; see docs/demos/11-ansible.md)"
}

# ----------------------------------------------------------------------------- bootstrap (idempotent)
bootstrap() {
  need jq; need curl
  aap_ready || die "AAP is not reachable yet: ./deploy.sh ansible setup"
  step "Project (this repository's ansible/ folder, from GitLab)"
  local org_id proj_id scm_url
  org_id=$(aap_get_id organizations Default)
  scm_url=$(gitlab_url_with_token)
  [[ -n "$scm_url" ]] || die "GitLab is not set up yet (./deploy.sh gitlab) -- the Project needs it as the Git source"
  proj_id=$(aap_get_id projects platform-ansible)
  if [[ -z "$proj_id" ]]; then
    proj_id=$(aap_api POST /api/controller/v2/projects/ "$(jq -n --arg org "$org_id" --arg url "$scm_url" '{
      name: "platform-ansible", organization: ($org|tonumber), scm_type: "git",
      scm_url: $url, scm_branch: "main", scm_update_on_launch: true, scm_clean: true}')" | jq -r '.id')
    # Bearer token is resolved once, here, and baked into the literal command string below --
    # bash -c forks a new shell that doesn't inherit this script's functions, same reason the
    # pods-ready check further up only shells out to "oc", never to our own aap_* helpers.
    wait_until 180 "Project sync" bash -c "[[ \$(curl -sk -H 'Authorization: Bearer $(aap_bearer)' '$(aap_url)/api/controller/v2/projects/${proj_id}/' 2>/dev/null | jq -r .status) == successful ]]"
    ok "Project platform-ansible created and synced"
  else
    aap_api POST "/api/controller/v2/projects/${proj_id}/update/" >/dev/null || true
    ok "Project platform-ansible already exists (re-synced)"
  fi

  step "Credential: OpenShift/Kubernetes API bearer token (scoped to namespace ${DEMO_NS} only)"
  local cred_type_id cred_id token
  cred_type_id=$(aap_api GET "/api/controller/v2/credential_types/?name=$(jq -rn --arg v 'OpenShift or Kubernetes API Bearer Token' '$v|@uri')" | jq -r '.results[0].id')
  token=$(oc get secret ansible-postgres-admin-token -n "$DEMO_NS" -o jsonpath='{.data.token}' | base64 -d)
  cred_id=$(aap_get_id credentials ansible-demo-cluster)
  if [[ -z "$cred_id" ]]; then
    aap_api POST /api/controller/v2/credentials/ "$(jq -n --arg org "$org_id" --arg ct "$cred_type_id" --arg tok "$token" '{
      name: "ansible-demo-cluster", organization: ($org|tonumber), credential_type: ($ct|tonumber),
      inputs: {host: "https://kubernetes.default.svc", bearer_token: $tok, verify_ssl: false}}' )" >/dev/null
    ok "Credential ansible-demo-cluster created"
  else
    aap_api PATCH "/api/controller/v2/credentials/${cred_id}/" "$(jq -n --arg tok "$token" '{inputs: {host: "https://kubernetes.default.svc", bearer_token: $tok, verify_ssl: false}}')" >/dev/null
    ok "Credential ansible-demo-cluster token refreshed"
  fi
  cred_id=$(aap_get_id credentials ansible-demo-cluster)

  step "Inventory (single localhost -- every task talks to the OpenShift API, not SSH)"
  local inv_id
  inv_id=$(aap_get_id inventories "Demo Inventory")
  if [[ -z "$inv_id" ]]; then
    inv_id=$(aap_api POST /api/controller/v2/inventories/ "$(jq -n --arg org "$org_id" '{name: "Demo Inventory", organization: ($org|tonumber)}')" | jq -r '.id')
    aap_api POST "/api/controller/v2/inventories/${inv_id}/hosts/" '{"name":"localhost","variables":"ansible_connection: local\nansible_python_interpreter: \"{{ ansible_playbook_python }}\""}' >/dev/null
    local group_id; group_id=$(aap_api POST "/api/controller/v2/inventories/${inv_id}/groups/" '{"name":"demo"}' | jq -r '.id')
    local host_id; host_id=$(aap_api GET "/api/controller/v2/inventories/${inv_id}/hosts/?name=localhost" | jq -r '.results[0].id')
    aap_api POST "/api/controller/v2/groups/${group_id}/hosts/" "{\"id\": ${host_id}}" >/dev/null
    ok "Inventory 'Demo Inventory' created (group 'demo', matching playbooks' hosts: demo)"
  else
    ok "Inventory 'Demo Inventory' already exists"
  fi

  step "Job Templates (ansible/job-templates.json)"
  local jt_id name playbook desc
  while IFS=$'\t' read -r name playbook desc; do
    jt_id=$(aap_get_id job_templates "$name")
    if [[ -z "$jt_id" ]]; then
      jt_id=$(aap_api POST /api/controller/v2/job_templates/ "$(jq -n --arg n "$name" --arg p "$playbook" --arg d "$desc" --arg proj "$proj_id" --arg inv "$inv_id" '{
        name: $n, description: $d, job_type: "run", project: ($proj|tonumber), playbook: $p,
        inventory: ($inv|tonumber), ask_variables_on_launch: false}')" | jq -r '.id')
      aap_api POST "/api/controller/v2/job_templates/${jt_id}/credentials/" "{\"id\": ${cred_id}}" >/dev/null
      ok "Job Template '${name}' created"
    else
      ok "Job Template '${name}' already exists"
    fi
  done < <(jq -r '.[] | [.name, .playbook, .description] | @tsv' "${ROOT_DIR}/ansible/job-templates.json")

  create_workflow "${ROOT_DIR}/ansible/workflows/install-postgres-safe.json" "$org_id"
  create_workflow "${ROOT_DIR}/ansible/workflows/delete-postgres.json" "$org_id"

  step "Developer Hub API token"
  local api_token
  api_token=$(oc get secret rhdh-ansible-token -n "$AAP_NS" -o jsonpath='{.data.token}' 2>/dev/null | base64 -d 2>/dev/null || true)
  if [[ -z "$api_token" ]]; then
    # Same Gateway token endpoint aap_bearer() uses for the script's own session, just with a
    # description that identifies it as the long-lived one Developer Hub keeps using afterwards.
    api_token=$(curl -sk -u "${ADMIN_USER}:$(aap_admin_password)" -X POST -H 'Content-Type: application/json' \
      -d '{"description":"Developer Hub (ansible-plugin-backstage-rhaap / software templates)","scope":"write"}' \
      "$(aap_url)/api/gateway/v1/tokens/" | jq -r '.token // empty')
    [[ -n "$api_token" ]] || die "could not create an AAP Platform Gateway token"
    oc create secret generic rhdh-ansible-token -n "$AAP_NS" --from-literal=token="$api_token" >/dev/null
    ok "token created and saved to Secret rhdh-ansible-token/${AAP_NS}"
  else
    ok "token already exists (./deploy.sh ansible token to view it)"
  fi
}

# node_id_set/node_id_get: identifier -> node ID lookup for create_workflow(), using two parallel
# indexed arrays instead of an associative array (`declare -A`) -- macOS ships bash 3.2 by
# default, which has no associative arrays at all (bash 4+ only); indexed arrays and dynamic
# scoping of a caller's `local` variables into the functions it calls both work fine in bash 3.2,
# so this stays portable without requiring the caller to `brew install bash`.
node_id_set() { node_id_keys+=("$1"); node_id_vals+=("$2"); }
node_id_get() {
  local i
  for i in "${!node_id_keys[@]}"; do
    [[ "${node_id_keys[$i]}" == "$1" ]] && { echo "${node_id_vals[$i]}"; return 0; }
  done
}

# create_workflow <json-file> <org_id>: nodes (job_template | workflow_approval_template) + edges
create_workflow() {
  local file=$1 org_id=$2 name wfjt_id
  name=$(jq -r '.name' "$file")
  wfjt_id=$(aap_get_id workflow_job_templates "$name")
  if [[ -n "$wfjt_id" ]]; then ok "Workflow '${name}' already exists (edit nodes by hand if ansible/workflows/${name}.json changed)"; return 0; fi
  wfjt_id=$(aap_api POST /api/controller/v2/workflow_job_templates/ "$(jq -n --arg n "$name" --arg d "$(jq -r '.description' "$file")" --arg org "$org_id" \
    '{name: $n, description: $d, organization: ($org|tonumber)}')" | jq -r '.id')

  local node_id_keys=() node_id_vals=()
  local identifier type ujt_name
  while IFS=$'\t' read -r identifier type ujt_name; do
    local node_id
    if [[ "$type" == workflow_approval_template ]]; then
      node_id=$(aap_api POST "/api/controller/v2/workflow_job_templates/${wfjt_id}/workflow_nodes/" '{}' | jq -r '.id')
      local desc timeout; desc=$(jq -r --arg i "$identifier" '.nodes[] | select(.identifier==$i) | .unified_job_template.description' "$file")
      timeout=$(jq -r --arg i "$identifier" '.nodes[] | select(.identifier==$i) | .unified_job_template.timeout' "$file")
      aap_api POST "/api/controller/v2/workflow_job_template_nodes/${node_id}/create_approval_template/" \
        "$(jq -n --arg n "$ujt_name" --arg d "$desc" --arg t "$timeout" '{name: $n, description: $d, timeout: ($t|tonumber)}')" >/dev/null
    else
      local jt_id; jt_id=$(aap_get_id job_templates "$ujt_name")
      [[ -n "$jt_id" ]] || die "Job Template '${ujt_name}' referenced by ${file} does not exist yet -- run bootstrap again"
      node_id=$(aap_api POST "/api/controller/v2/workflow_job_templates/${wfjt_id}/workflow_nodes/" "$(jq -n --arg jt "$jt_id" '{unified_job_template: ($jt|tonumber)}')" | jq -r '.id')
    fi
    node_id_set "$identifier" "$node_id"
  done < <(jq -r '.nodes[] | [.identifier, .unified_job_template.type, .unified_job_template.name] | @tsv' "$file")

  local from to state relation
  while IFS=$'\t' read -r from to state; do
    case "$state" in success) relation=success_nodes ;; failure) relation=failure_nodes ;; *) relation=always_nodes ;; esac
    aap_api POST "/api/controller/v2/workflow_job_template_nodes/$(node_id_get "$from")/${relation}/" "{\"id\": $(node_id_get "$to")}" >/dev/null
  done < <(jq -r '.edges[] | [.from, .to, .state] | @tsv' "$file")
  ok "Workflow '${name}' created ($(jq '.nodes | length' "$file") nodes, $(jq '.edges | length' "$file") edges)"
}

# ----------------------------------------------------------------------------- day 2
token() {
  local t; t=$(oc get secret rhdh-ansible-token -n "$AAP_NS" -o jsonpath='{.data.token}' 2>/dev/null | base64 -d 2>/dev/null)
  [[ -n "$t" ]] || die "no token yet: ./deploy.sh ansible setup"
  echo "$t"
  warn "sensitive: this is the value for ansible.rhaap.token (Developer Hub) and the Ansible software templates' Token field"
}

urls() {
  echo "AAP Platform Gateway:          $(aap_url)"
  echo "Admin password:                oc get secret ${AAP_CR}-${ADMIN_USER}-password -n ${AAP_NS} -o jsonpath='{.data.password}' | base64 -d"
  echo "API token for Developer Hub:   ./deploy.sh ansible token"
  echo "Controller API (behind the gateway): $(aap_url)/api/controller/v2/"
}

run() {
  local wf=${1:?usage: ./deploy.sh ansible run <install-postgres-safe|delete-postgres>}
  local wfjt_id; wfjt_id=$(aap_get_id workflow_job_templates "$wf")
  [[ -n "$wfjt_id" ]] || die "no such workflow '${wf}': ./deploy.sh ansible setup first"
  local job_id; job_id=$(aap_api POST "/api/controller/v2/workflow_job_templates/${wfjt_id}/launch/" '{}' | jq -r '.id // .workflow_job // empty')
  [[ -n "$job_id" ]] || die "launch failed: check $(aap_url)/#/jobs"
  ok "launched workflow job ${job_id}: $(aap_url)/#/jobs/workflow/${job_id}/output"
}

approve_deny() {
  local action=$1 id=${2:-}
  [[ -n "$id" ]] || id=$(aap_api GET "/api/controller/v2/workflow_approvals/?status=pending&order_by=-created" | jq -r '.results[0].id // empty')
  [[ -n "$id" ]] || die "no pending approval found"
  aap_api POST "/api/controller/v2/workflow_approvals/${id}/${action}/" '{}' >/dev/null
  ok "${action}d approval ${id}"
}

status() {
  echo "-- Demo PostgreSQL (namespace ${DEMO_NS})"
  oc get deployment,svc,pvc -n "$DEMO_NS" -l managed-by=ansible 2>/dev/null || echo "  (not installed)"
  echo "-- Pending AAP approvals"
  aap_ready && aap_api GET "/api/controller/v2/workflow_approvals/?status=pending" 2>/dev/null | jq -r '.results[] | "  \(.id)\t\(.name)\t(launched \(.created))"' || echo "  AAP not reachable"
}

reset() {
  step "Removing the demo PostgreSQL directly (not through Ansible -- for a clean demo start)"
  oc delete deployment,svc,pvc,secret -n "$DEMO_NS" -l managed-by=ansible --ignore-not-found >/dev/null
  ok "ansible-demo is now empty; the next 'install-postgres-safe' run installs straight away (no approval needed)"
}

destroy() {
  step "Removing the Ansible demo (operator Subscription/CSV stay installed)"
  oc delete namespace "$DEMO_NS" --ignore-not-found >/dev/null
  oc delete namespace "$AAP_NS" --ignore-not-found >/dev/null
  ok "namespaces ${DEMO_NS} and ${AAP_NS} deleted"
}

# ----------------------------------------------------------------------------- main
[[ $# -ge 1 ]] || { echo "usage: ./deploy.sh ansible <setup|bootstrap|token|urls|run|approve|deny|status|reset|destroy>"; exit 1; }
CMD=$1; shift
case "$CMD" in
  setup) setup ;;
  bootstrap) bootstrap ;;
  token) token ;;
  urls) urls ;;
  run) run "${1:-}" ;;
  approve) approve_deny approve "${1:-}" ;;
  deny) approve_deny deny "${1:-}" ;;
  status) status ;;
  reset) reset ;;
  destroy) destroy ;;
  *) die "unknown command '${CMD}'" ;;
esac
